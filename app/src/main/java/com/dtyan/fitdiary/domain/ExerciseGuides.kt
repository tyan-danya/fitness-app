    /** Public for artwork coverage and catalog tests; keys are independent of database IDs. */
    val all: List<ExerciseGuide> = entries.map { it.guide }

    fun forExercise(exercise: Exercise): ExerciseGuide = resolve(exercise.name, exercise.equipment)

    fun resolve(name: String, equipment: String = ""): ExerciseGuide {
        val normalizedName = normalize(name)
        val normalizedEquipment = equipmentCategory(equipment)
        val found = entries.firstOrNull { entry ->
            (normalize(entry.guide.title) == normalizedName || entry.aliases.any { normalize(it) == normalizedName }) &&
                (equipment.isBlank() || equipmentCategory(entry.equipment) == normalizedEquipment)
        }
        return found?.guide ?: generic(equipment)
    }

    fun forActivity(definition: ActivityDefinition): ExerciseGuide {
        val found = activityEntry(definition.key, definition.name)
        return found?.takeIf { it.activityKind == definition.kind }?.guide ?: generic("Своё тело")
    }

    /** Import-preview overload: stable key alone never overrides a contradictory exercise name. */
    fun forActivity(key: String, name: String): ExerciseGuide =
        activityEntry(key, name)?.guide ?: generic("Своё тело")

    private fun activityEntry(key: String, name: String): Entry? {
        val normalizedName = normalize(name)
        return entries.firstOrNull { entry ->
            entry.activityKind != null && entry.guide.key == key.trim() &&
                (normalize(entry.guide.title) == normalizedName || entry.aliases.any { normalize(it) == normalizedName })
        }
    }

    internal fun normalize(value: String): String = Normalizer.normalize(value, Normalizer.Form.NFKC)
        .lowercase(Locale.ROOT).replace('ё', 'е')
        .replace(Regex("[‐‑‒–—−-]+"), " ")
        .replace(Regex("[\\s\\p{Z}]+"), " ").trim()

    private fun equipmentCategory(value: String): String = when (normalize(value)) {
        "тренажер", "machine" -> "machine"
        "штанга", "barbell" -> "barbell"
        "гантели", "dumbbells" -> "dumbbells"
        "блок", "cable" -> "cable"
        "свое тело", "свой вес", "собственный вес", "bodyweight" -> "bodyweight"
        else -> "other"
    }

    private fun generic(equipment: String): ExerciseGuide {
        val category = equipmentCategory(equipment)
        val (title, description) = when (category) {
            "machine" -> "Тренажёр" to "Точная модель по этому названию не определена. Сверьте фото и табличку на машине."
            "barbell" -> "Штанга" to "Гриф с дисками. Положение тела, стоек и страховки зависит от конкретного упражнения."
            "dumbbells" -> "Гантели" to "Отдельный вес в каждой руке. По названию не удалось определить движение."
            "cable" -> "Блочный тренажёр" to "Трос, ролик и сменная рукоять. Высота блока и направление тяги зависят от упражнения."
            "bodyweight" -> "Упражнение с собственным весом" to "Название не совпало со справочником. Точная постановка и движение не определены."
            else -> "Оборудование не определено" to "Для этого названия пока нет точной инструкции в справочнике."
